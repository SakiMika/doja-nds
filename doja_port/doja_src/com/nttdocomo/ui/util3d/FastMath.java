package com.nttdocomo.ui.util3d;

public final class FastMath {
    private FastMath() {
    }

    public static float sin(float value) { return (float)java.lang.Math.sin(value); }
    public static float cos(float value) { return (float)java.lang.Math.cos(value); }
    public static float tan(float value) { return (float)java.lang.Math.tan(value); }
    public static float sqrt(float value) { return (float)java.lang.Math.sqrt(value); }
}
